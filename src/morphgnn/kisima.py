"""Kisima: a small, fully documented synthetic morphologically rich language.

Kisima is invented for this repository. It is deliberately simple to state
and audit, while exhibiting three properties that make real morphologically
complex languages (Plains Cree, Kunwinjku, Finnish, Turkish, Irish) hard
for sequence models:

1. **Agglutination with fixed templatic slots.** A verb is
   ``NEG - SUBJ - TENSE - ROOT - OBJ - MOOD``; a noun is
   ``POSS - ROOT - NUM - CASE``. Word length and morpheme count vary,
   so the "word" is a sequence of meaningful parts, not an atomic unit.

2. **Vowel harmony (non-local agreement).** Every suffix vowel agrees
   with the harmony class (front ``i e`` / back ``a o u``) of the root's
   *last* vowel. The correct surface form of a suffix therefore depends
   on a segment that can be arbitrarily far away in the string. This is
   the canonical case where graph structure (long-range edges) can beat
   local sequence windows.

3. **Paradigms.** Each lexeme defines a grid of forms (person x tense x
   mood for verbs). Forms of one lexeme share most of their material,
   which makes paradigm completion -- predict a held-out cell from its
   neighbours -- a natural link-prediction problem.

Everything is generated by explicit rules below, so every label in every
dataset is exactly correct by construction, and every experiment in this
repository can be audited end to end. The cost is honesty about scope:
Kisima has no allomorphy beyond harmony, no fusional exponence, no
suppletion, and no phonology beyond concatenation. It is a wind tunnel,
not the weather. The final tutorial (05) is about that gap.
"""
from __future__ import annotations

import random
from dataclasses import dataclass

FRONT = set("ie")
BACK = set("aou")

# --- phoneme-ish inventory (characters are the graph nodes) -----------------
CONSONANTS = list("ptkmnslrwy")
VOWELS = list("aieou")

# --- morpheme inventory ------------------------------------------------------
# Each affix has two allomorphs: (front, back) selected by root harmony.
# A single-form tuple means the morpheme is harmony-neutral.
NEG = ("ke", "ka")            # verbs only, optional slot 0
SUBJ = {  # person.number
    "1sg": ("ni", "nu"), "2sg": ("ti", "tu"), "3sg": ("", ""),
    "1pl": ("nimi", "numu"), "2pl": ("timi", "tumu"), "3pl": ("mi", "mu"),
}
TENSE = {"past": ("li", "lu"), "pres": ("", ""), "fut": ("ta", "ta")}
OBJ = {"none": ("", ""), "3sg.obj": ("ki", "ku"), "3pl.obj": ("kimi", "kumu")}
MOOD = {"ind": ("", ""), "imp": ("pe", "po"), "neg.imp": ("pesi", "posu")}

POSS = {"1sg.poss": ("ni", "nu"), "2sg.poss": ("ti", "tu"), "none": ("", "")}
NUM = {"sg": ("", ""), "pl": ("wi", "wa")}
CASE = {"nom": ("", ""), "acc": ("ni", "na"), "loc": ("ti", "ta"), "gen": ("ya", "ya")}


def harmony(root: str) -> int:
    """0 = front, 1 = back, from the root's last vowel."""
    for ch in reversed(root):
        if ch in FRONT:
            return 0
        if ch in BACK:
            return 1
    return 1


@dataclass
class Word:
    """A generated word with full morphological annotation.

    ``morphs`` is a list of (slot, gloss, surface) triples, e.g.
    ("SUBJ", "1sg", "ni"). Empty surface = zero exponent (kept in the
    annotation so tasks can require predicting invisible structure).
    """
    surface: str
    lemma: str
    pos: str  # "V" or "N"
    morphs: list[tuple[str, str, str]]
    harmony: int  # 0 front, 1 back

    @property
    def boundaries(self) -> list[int]:
        """Character offsets where a non-empty morpheme boundary falls."""
        out, acc = [], 0
        parts = [s for _, _, s in self.morphs if s]
        for part in parts[:-1]:
            acc += len(part)
            out.append(acc)
        return out

    @property
    def feature_string(self) -> str:
        return ".".join(g for _, g, _ in self.morphs if g != "ROOT")


def make_root(rng: random.Random, syllables: int = 2) -> str:
    return "".join(rng.choice(CONSONANTS) + rng.choice(VOWELS) for _ in range(syllables))


def build_verb(root: str, subj: str, tense: str, obj: str, mood: str, neg: bool) -> Word:
    h = harmony(root)
    morphs: list[tuple[str, str, str]] = []
    if neg:
        morphs.append(("NEG", "NEG", NEG[h]))
    morphs += [
        ("SUBJ", subj, SUBJ[subj][h]),
        ("TENSE", tense, TENSE[tense][h]),
        ("ROOT", root, root),
        ("OBJ", obj, OBJ[obj][h]),
        ("MOOD", mood, MOOD[mood][h]),
    ]
    return Word("".join(s for _, _, s in morphs), root, "V", morphs, h)


def build_noun(root: str, poss: str, num: str, case: str) -> Word:
    h = harmony(root)
    morphs = [
        ("POSS", poss, POSS[poss][h]),
        ("ROOT", root, root),
        ("NUM", num, NUM[num][h]),
        ("CASE", case, CASE[case][h]),
    ]
    return Word("".join(s for _, _, s in morphs), root, "N", morphs, h)


def generate_lexicon(seed: int = 0, n_verbs: int = 40, n_nouns: int = 40) -> dict[str, list[Word]]:
    """Full paradigms for a small lexicon. Deterministic given the seed."""
    rng = random.Random(seed)
    lex: dict[str, list[Word]] = {}
    roots: set[str] = set()
    while len(roots) < n_verbs + n_nouns:
        roots.add(make_root(rng, syllables=rng.choice([2, 2, 3])))
    roots = sorted(roots)
    for root in roots[:n_verbs]:
        lex[root] = [
            build_verb(root, s, t, o, m, neg)
            for s in SUBJ for t in TENSE for o in OBJ for m in MOOD
            for neg in (False, True)
            if not (neg and m == "neg.imp")  # NEG prefix and neg.imp are redundant
        ]
    for root in roots[n_verbs:]:
        lex[root] = [build_noun(root, p, n, c) for p in POSS for n in NUM for c in CASE]
    return lex


if __name__ == "__main__":
    lexicon = generate_lexicon()
    total = sum(len(v) for v in lexicon.values())
    print(f"Kisima lexicon: {len(lexicon)} lexemes, {total} word forms")
    for form in list(lexicon.values())[0][:5]:
        print(" ", form.surface, "|", " + ".join(f"{g}:{s or '0'}" for _, g, s in form.morphs))
